
let x = 7;
let y = 3;

console.log("Arithmetic Operators")
console.log(x + y);
console.log(x - y);
console.log(x * y);
console.log(x / y);
console.log(x % y);

console.log("post increment value")
console.log(x++);
console.log(y++);

console.log("decrement value")
console.log(x--);
console.log(y--);

console.log("pre increment")
console.log(++x);
console.log(++y);
console.log(--x);
console.log(--y);

console.log("this is optional")
console.log(y - x);
console.log(y / x);

